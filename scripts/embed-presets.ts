#!/usr/bin/env bun
/**
 * Menanam seluruh isi folder presets/ ke src/generated/presets.generated.ts
 * supaya binary hasil `bun build --compile` tetap membawa persona bawaan
 * dan bisa dijalankan dari direktori mana pun.
 *
 * Usage: bun run scripts/embed-presets.ts [--check]
 *   --check  gagal (exit 1) jika file generated tidak sinkron dengan presets/
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const PRESETS = join(ROOT, "presets");
const OUT = join(ROOT, "src/generated/presets.generated.ts");
const KIND_DIRS = ["personas", "roles", "traits", "harnesses"];

export function buildEmbeddedSource(): string {
  const entries: Array<[string, string]> = [];
  for (const kindDir of KIND_DIRS) {
    const dir = join(PRESETS, kindDir);
    if (!existsSync(dir)) continue;
    const files = (readdirSync(dir, { recursive: true }) as string[])
      .filter((f) => [".yaml", ".yml", ".json"].includes(extname(f)))
      .sort();
    for (const f of files) {
      const full = join(dir, f);
      entries.push([relative(PRESETS, full).split("\\").join("/"), readFileSync(full, "utf-8")]);
    }
  }

  const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  return `// AUTO-GENERATED by scripts/embed-presets.ts — jangan diedit manual.
// Jalankan \`bun run embed\` setelah mengubah isi folder presets/.
export const EMBEDDED_PRESETS: Record<string, string> = {
${body}
};
`;
}

if (import.meta.main) {
  const source = buildEmbeddedSource();
  const current = existsSync(OUT) ? readFileSync(OUT, "utf-8") : "";
  if (process.argv.includes("--check")) {
    if (current !== source) {
      console.error("✖ src/generated/presets.generated.ts tidak sinkron. Jalankan: bun run embed");
      process.exit(1);
    }
    console.log("✔ Embedded presets sinkron.");
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, source, "utf-8");
    const count = (source.match(/^ {2}"/gm) ?? []).length;
    console.log(`✔ ${count} preset ditanam ke ${relative(ROOT, OUT)}`);
  }
}
