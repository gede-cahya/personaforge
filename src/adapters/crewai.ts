import type { HarnessAdapter, HarnessOutput } from "./base.ts";
import type { PersonaSpec } from "../schema/ups.ts";

export class CrewAIAdapter implements HarnessAdapter {
  readonly id = "crewai";
  readonly name = "CrewAI Agent Harness";
  readonly description = "Kode Python Agent class siap pakai untuk framework CrewAI";

  compile(persona: PersonaSpec): HarnessOutput {
    const { identity, linguistic_style, reasoning_protocol } = persona;

    const role = `${persona.name} (${identity.title})`;
    const goal = `Execute tasks with ${reasoning_protocol.mode} precision, maintaining a ${linguistic_style.tone} communication standard.`;
    const backstory = `${identity.bio} ${identity.lore.join(" ")} Strict guidelines: ${linguistic_style.forbidden_patterns.join("; ")}`;

    const content = `from crewai import Agent

# Generated by PersonaForge for CrewAI
agent_${persona.id.replace(/-/g, "_")} = Agent(
    role="""${role}""",
    goal="""${goal}""",
    backstory="""${backstory}""",
    verbose=True,
    memory=True,
    allow_delegation=False,
    # tools=[...], # Add your specific tools here
)
`;

    return {
      harnessId: this.id,
      filename: `agent_${persona.id.replace(/-/g, "_")}.py`,
      mimeType: "text/x-python",
      content,
      metadata: {
        role,
        goal,
      },
    };
  }
}
