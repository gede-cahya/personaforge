import type { HarnessAdapter, HarnessOutput } from "./base.ts";
import type { PromptIR } from "../core/ir.ts";
import { renderPrompt } from "../core/render.ts";
import { escapePyTriple, safeIdentifier } from "../core/escape.ts";

export class CrewAIAdapter implements HarnessAdapter {
  readonly id = "crewai";
  readonly name = "CrewAI Agent Harness";
  readonly description = "Kode Python Agent class siap pakai untuk framework CrewAI";
  readonly category = "framework";

  compile(ir: PromptIR): HarnessOutput {
    const varName = `agent_${safeIdentifier(ir.persona.id)}`;
    const role = `${ir.persona.name}${ir.role ? ` (${ir.role.name})` : ""}`;
    const goal = ir.persona.tagline || `Execute tasks with ${ir.persona.voice.tone} style and high excellence`;
    const backstory = renderPrompt(ir, { style: "markdown" });

    const content = `from crewai import Agent

# Generated by PersonaForge for CrewAI
${varName} = Agent(
    role="""${escapePyTriple(role)}""",
    goal="""${escapePyTriple(goal)}""",
    backstory="""${escapePyTriple(backstory)}""",
    verbose=True,
    memory=True,
    allow_delegation=False,
    # tools=[...], # Add your specific tools here
)
`;

    return {
      harnessId: this.id,
      filename: `agent_${safeIdentifier(ir.persona.id)}.py`,
      mimeType: "text/x-python",
      content,
      metadata: {
        role,
        goal,
      },
    };
  }
}
